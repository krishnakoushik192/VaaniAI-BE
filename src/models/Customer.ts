import mongoose, { Schema, type HydratedDocument, type Types } from 'mongoose';
import type { Paise } from '../lib/money.js';
import { cleanJSON } from '../lib/toJSON.js';

export const RECENT_LIMIT = 3;

export const TXN_KINDS = ['bill', 'payment'] as const;
export const PAYMENT_METHODS = ['cash', 'upi', 'khata'] as const;
export type TxnKind = (typeof TXN_KINDS)[number];
export type PaymentMethod = (typeof PAYMENT_METHODS)[number];

export interface ITxnItem {
  name: string;
  qty: number;
  unit?: string; // kg, L, pc …
  rate: Paise; // per unit
}

export interface IRecentTransaction {
  txnId: string; // generated by the app; the same txnId is never recorded twice
  kind: TxnKind;
  method: PaymentMethod;
  amount: Paise;
  billNo?: string;
  items?: ITxnItem[];
  discount?: Paise;
  createdAt: Date;
}

export interface ICustomer {
  shopkeeperId: Types.ObjectId;
  customerName: string;
  phoneNumber?: string;
  isWalkinCustomer: boolean;
  pastDues: Paise; // owed to the shop
  dueSince?: Date; // when the current unpaid balance started
  recentTransactions: IRecentTransaction[]; // newest last, max RECENT_LIMIT
  createdAt?: Date;
  updatedAt?: Date;
}

export type CustomerDoc = HydratedDocument<ICustomer>;

const itemSchema = new Schema<ITxnItem>(
  {
    name: { type: String, required: true, trim: true },
    qty: { type: Number, required: true, min: 0 },
    unit: { type: String, trim: true, default: 'pc' },
    rate: { type: Number, required: true, min: 0, validate: Number.isInteger },
  },
  { _id: false },
);

const recentTransactionSchema = new Schema<IRecentTransaction>(
  {
    txnId: { type: String, required: true },
    kind: { type: String, enum: TXN_KINDS, required: true },
    method: { type: String, enum: PAYMENT_METHODS, required: true },
    amount: { type: Number, required: true, validate: Number.isInteger },
    billNo: String,
    items: { type: [itemSchema], default: undefined },
    discount: { type: Number, validate: Number.isInteger },
    createdAt: { type: Date, default: Date.now },
  },
  { _id: false },
);

const customerSchema = new Schema<ICustomer>(
  {
    shopkeeperId: { type: Schema.Types.ObjectId, ref: 'Shopkeeper', required: true, index: true },
    customerName: { type: String, required: true, trim: true, maxlength: 100 },
    phoneNumber: { type: String, match: /^[6-9]\d{9}$/ },
    isWalkinCustomer: { type: Boolean, default: false },
    pastDues: { type: Number, default: 0, min: 0, validate: Number.isInteger },
    dueSince: Date,
    recentTransactions: { type: [recentTransactionSchema], default: [] },
  },
  {
    timestamps: true,
    toJSON: { transform: cleanJSON() },
  },
);

// A phone number is unique within one shop (two shops can share a customer).
customerSchema.index(
  { shopkeeperId: 1, phoneNumber: 1 },
  { unique: true, partialFilterExpression: { phoneNumber: { $type: 'string' } } },
);
// Each shop has exactly one shared "Walk-in" customer for anonymous cash/UPI sales.
customerSchema.index(
  { shopkeeperId: 1, isWalkinCustomer: 1 },
  { unique: true, partialFilterExpression: { isWalkinCustomer: true } },
);

export const Customer = mongoose.model<ICustomer>('Customer', customerSchema);
